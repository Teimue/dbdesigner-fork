/* =============================================================================
   Trigger
   ============================================================================= */
CREATE TRIGGER TRG_KUNDE_BI FOR KUNDE
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.KUNDE_ID IS NULL) THEN
    NEW.KUNDE_ID = NEXT VALUE FOR SEQ_KUNDE;
  IF (NEW.KUNDENNR IS NULL) THEN
    NEW.KUNDENNR = 'K' || LPAD(GEN_ID(SEQ_KUNDENNR, 1), 5, '0');
END^

CREATE TRIGGER TRG_PROTOKOLL_BI FOR PROTOKOLL
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.PROTOKOLL_ID IS NULL) THEN
    NEW.PROTOKOLL_ID = GEN_ID(SEQ_PROTOKOLL, 1);
END^

/* Ein Trigger fuer mehrere Ereignisse, mit INSERTING/UPDATING/DELETING */
CREATE TRIGGER TRG_ARTIKEL_AIUD FOR ARTIKEL
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE AKTION VARCHAR(6);
BEGIN
  AKTION = CASE WHEN INSERTING THEN 'INSERT' WHEN UPDATING THEN 'UPDATE' ELSE 'DELETE' END;
  INSERT INTO PROTOKOLL (TABELLE, AKTION, SCHLUESSEL, ALT, NEU)
  VALUES ('ARTIKEL', :AKTION, COALESCE(NEW.ARTIKEL_ID, OLD.ARTIKEL_ID),
          OLD.BEZEICHNUNG || ' / ' || OLD.NETTO_PREIS,
          NEW.BEZEICHNUNG || ' / ' || NEW.NETTO_PREIS);
END^

CREATE TRIGGER TRG_ARTIKEL_BU FOR ARTIKEL
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
  IF (NEW.NETTO_PREIS IS DISTINCT FROM OLD.NETTO_PREIS OR
      NEW.BEZEICHNUNG IS DISTINCT FROM OLD.BEZEICHNUNG) THEN
    NEW.GEAENDERT_AM = CURRENT_TIMESTAMP;
END^

CREATE TRIGGER TRG_BESTELLUNG_BU FOR BESTELLUNG
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
  IF (OLD.STATUS = 'versandt' AND NEW.STATUS = 'storniert') THEN
    EXCEPTION E_STORNO_VERBOTEN;
END^

CREATE TRIGGER TRG_POSITION_AIUD FOR BESTELLPOSITION
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 0
AS
  DECLARE VARIABLE BID BIGINT;
BEGIN
  BID = COALESCE(NEW.BESTELLUNG_ID, OLD.BESTELLUNG_ID);
  UPDATE BESTELLUNG
     SET SUMME_NETTO = (SELECT COALESCE(SUM(GESAMTPREIS), 0) FROM BESTELLPOSITION
                         WHERE BESTELLUNG_ID = :BID)
   WHERE BESTELLUNG_ID = :BID;
END^

