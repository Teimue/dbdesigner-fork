   Views
   ============================================================================= */
CREATE VIEW V_BESTELLUEBERSICHT (BESTELLUNG_ID, KUNDENNR, NACHNAME, BESTELLT_AM,
                                 STATUS, POSITIONEN, SUMME)
AS
  SELECT B.BESTELLUNG_ID, K.KUNDENNR, K.NACHNAME, B.BESTELLT_AM, B.STATUS,
         COUNT(P.POS_NR), COALESCE(SUM(P.GESAMTPREIS), 0)
    FROM BESTELLUNG B
    JOIN KUNDE K ON K.KUNDE_ID = B.KUNDE_ID
    LEFT JOIN BESTELLPOSITION P ON P.BESTELLUNG_ID = B.BESTELLUNG_ID
   GROUP BY B.BESTELLUNG_ID, K.KUNDENNR, K.NACHNAME, B.BESTELLT_AM, B.STATUS;

/* Aenderbare View mit WITH CHECK OPTION */
CREATE VIEW V_AKTIVE_KATEGORIEN AS
  SELECT KATEGORIE_ID, ELTERN_ID, NAME, SORTIERUNG, AKTIV
    FROM KATEGORIE
   WHERE AKTIV = TRUE
  WITH CHECK OPTION;

/* Fensterfunktionen */
CREATE VIEW V_ARTIKEL_RANG AS
  SELECT A.ARTIKEL_ID, A.BEZEICHNUNG, A.KATEGORIE_ID, A.NETTO_PREIS,
         RANK() OVER (PARTITION BY A.KATEGORIE_ID ORDER BY A.NETTO_PREIS DESC) AS PREISRANG,
         SUM(A.NETTO_PREIS) OVER (PARTITION BY A.KATEGORIE_ID) AS KATEGORIESUMME
    FROM ARTIKEL A;

COMMENT ON VIEW V_BESTELLUEBERSICHT IS 'Bestellungen mit Kunde und Summe';

