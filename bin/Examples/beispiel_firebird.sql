/* -----------------------------------------------------------------------------
   Artikel: berechnete Spalten (COMPUTED BY und GENERATED ALWAYS AS), Domaenen,
   benannte CHECKs, Indizes (absteigend, eindeutig, Ausdruck, partiell)
   ----------------------------------------------------------------------------- */
CREATE TABLE ARTIKEL (
  ARTIKEL_ID        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ARTIKELNR         CHAR(12) CHARACTER SET ASCII NOT NULL,
  KATEGORIE_ID      INTEGER NOT NULL,
  BEZEICHNUNG       VARCHAR(200) NOT NULL,
  BESCHREIBUNG      D_TEXT,
  NETTO_PREIS       D_GELD,
  MWST_SATZ         NUMERIC(4,2) DEFAULT 19.00 NOT NULL,
  BRUTTO_PREIS      COMPUTED BY (CAST(NETTO_PREIS * (1 + MWST_SATZ / 100) AS NUMERIC(12,2))),
  GEWICHT_KG        DOUBLE PRECISION,
  VERSANDKLASSE     GENERATED ALWAYS AS
                      (CASE WHEN GEWICHT_KG IS NULL THEN 'unbekannt'
                            WHEN GEWICHT_KG <= 2 THEN 'Paeckchen'
                            ELSE 'Paket' END),
  BILD              BLOB SUB_TYPE BINARY,
  ANGELEGT_AM       D_ZEITSTEMPEL,
  GEAENDERT_AM      TIMESTAMP WITH TIME ZONE,
  CONSTRAINT PK_ARTIKEL PRIMARY KEY (ARTIKEL_ID),
  CONSTRAINT UQ_ARTIKEL_NR UNIQUE (ARTIKELNR),
  CONSTRAINT CK_ARTIKEL_MWST CHECK (MWST_SATZ IN (0, 7, 19)),
  CONSTRAINT FK_ARTIKEL_KATEGORIE FOREIGN KEY (KATEGORIE_ID)
    REFERENCES KATEGORIE (KATEGORIE_ID) ON UPDATE CASCADE
);

CREATE INDEX IDX_ARTIKEL_KATEGORIE ON ARTIKEL (KATEGORIE_ID);
CREATE DESCENDING INDEX IDX_ARTIKEL_PREIS ON ARTIKEL (NETTO_PREIS);
CREATE UNIQUE INDEX IDX_ARTIKEL_BEZ ON ARTIKEL (BEZEICHNUNG, KATEGORIE_ID);
CREATE INDEX IDX_ARTIKEL_UPPER ON ARTIKEL COMPUTED BY (UPPER(BEZEICHNUNG));
CREATE INDEX IDX_ARTIKEL_SCHWER ON ARTIKEL (GEWICHT_KG) WHERE GEWICHT_KG > 30;

COMMENT ON TABLE ARTIKEL IS 'Artikelstamm des Shops';
COMMENT ON COLUMN ARTIKEL.ARTIKELNR IS 'Externe Artikelnummer, z. B. B-0000000001';
COMMENT ON COLUMN ARTIKEL.BRUTTO_PREIS IS 'Berechnet: Netto plus Mehrwertsteuer';

