/* =============================================================================
   Beispiel-Datenbank fuer Firebird 5 (die meisten Teile laufen ab Firebird 4)
   Ein kleiner Webshop, der die wichtigen SQL-Konstrukte und Datentypen von
   Firebird zeigt. Zum Reverse Engineering in DBDesigner Fork:
     Database > Reverse Engineering, Treiber Firebird, Datei beispiel.fdb

   Erzeugen der Datenbank (embedded, ohne Server):
     isql -user SYSDBA -i beispiel_firebird.sql
   Mit Server: CREATE DATABASE unten auf 'localhost:C:\...\beispiel.fdb'
   aendern und -password angeben.
   ============================================================================= */

SET SQL DIALECT 3;
SET NAMES UTF8;

CREATE DATABASE 'beispiel.fdb'
  PAGE_SIZE 16384
  DEFAULT CHARACTER SET UTF8 COLLATION UNICODE;

SET AUTODDL ON;

/* -----------------------------------------------------------------------------
   Domaenen: eigene Datentypen mit Default, NOT NULL und CHECK
   ----------------------------------------------------------------------------- */
CREATE DOMAIN D_ID          AS INTEGER NOT NULL;
CREATE DOMAIN D_BOOL        AS BOOLEAN DEFAULT FALSE NOT NULL;
CREATE DOMAIN D_GELD        AS NUMERIC(12,2) DEFAULT 0 NOT NULL CHECK (VALUE >= 0);
CREATE DOMAIN D_PROZENT     AS DECIMAL(5,2) DEFAULT 0 CHECK (VALUE BETWEEN 0 AND 100);
CREATE DOMAIN D_NAME        AS VARCHAR(80) CHARACTER SET UTF8 COLLATE UNICODE_CI;
CREATE DOMAIN D_EMAIL       AS VARCHAR(254) CHARACTER SET UTF8
  CHECK (VALUE IS NULL OR VALUE LIKE '%_@_%._%') COLLATE UNICODE_CI_AI;
CREATE DOMAIN D_LAND        AS CHAR(2) CHARACTER SET ASCII DEFAULT 'DE' NOT NULL;
CREATE DOMAIN D_STATUS      AS VARCHAR(12) DEFAULT 'neu' NOT NULL
  CHECK (VALUE IN ('neu', 'bezahlt', 'versandt', 'storniert'));
CREATE DOMAIN D_TEXT        AS BLOB SUB_TYPE TEXT SEGMENT SIZE 4096 CHARACTER SET UTF8;
CREATE DOMAIN D_ZEITSTEMPEL AS TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL;

COMMENT ON DOMAIN D_GELD IS 'Geldbetrag in Euro, nie negativ';

