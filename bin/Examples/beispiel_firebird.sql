/* -----------------------------------------------------------------------------
   Kategorie: Selbstbezug (Baum), Identity BY DEFAULT, eindeutiger Name je Ebene
   ----------------------------------------------------------------------------- */
CREATE TABLE KATEGORIE (
  KATEGORIE_ID      INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
  ELTERN_ID         INTEGER,
  NAME              D_NAME NOT NULL,
  SORTIERUNG        SMALLINT DEFAULT 0 NOT NULL,
  AKTIV             D_BOOL,
  CONSTRAINT PK_KATEGORIE PRIMARY KEY (KATEGORIE_ID),
  CONSTRAINT UQ_KATEGORIE_NAME UNIQUE (ELTERN_ID, NAME),
  CONSTRAINT CK_KATEGORIE_SORT CHECK (SORTIERUNG >= 0),
