/* Ausfuehrbare Prozedur mit Ausgabeparametern und Exception mit Parametern */
CREATE PROCEDURE SP_LAGER_ABBUCHEN (
  P_ARTIKEL_ID BIGINT,
  P_MENGE      INTEGER)
RETURNS (
  NEUER_BESTAND INTEGER)
AS
  DECLARE VARIABLE V_BESTAND INTEGER;
BEGIN
  SELECT BESTAND FROM LAGERBESTAND
   WHERE ARTIKEL_ID = :P_ARTIKEL_ID
    WITH LOCK
    INTO :V_BESTAND;
  IF (V_BESTAND < P_MENGE) THEN
    EXCEPTION E_BESTAND USING (P_ARTIKEL_ID, V_BESTAND);
  UPDATE LAGERBESTAND SET BESTAND = BESTAND - :P_MENGE
   WHERE ARTIKEL_ID = :P_ARTIKEL_ID
  RETURNING BESTAND INTO :NEUER_BESTAND;
END^

/* Selektierbare Prozedur mit FOR SELECT und SUSPEND */
CREATE PROCEDURE SP_KATEGORIE_BAUM (P_START INTEGER = NULL)
RETURNS (
  KATEGORIE_ID INTEGER,
  PFAD         VARCHAR(1000),
  TIEFE        SMALLINT)
AS
BEGIN
  FOR WITH RECURSIVE BAUM AS (
        SELECT KATEGORIE_ID, CAST(NAME AS VARCHAR(1000)) AS PFAD, CAST(0 AS SMALLINT) AS TIEFE
          FROM KATEGORIE
         WHERE (ELTERN_ID IS NULL AND :P_START IS NULL) OR KATEGORIE_ID = :P_START
        UNION ALL
        SELECT K.KATEGORIE_ID, B.PFAD || ' > ' || K.NAME, B.TIEFE + 1
          FROM KATEGORIE K JOIN BAUM B ON K.ELTERN_ID = B.KATEGORIE_ID)
      SELECT KATEGORIE_ID, PFAD, TIEFE FROM BAUM
      INTO :KATEGORIE_ID, :PFAD, :TIEFE
  DO
    SUSPEND;
END^

/* PSQL-Funktion (ab Firebird 3) */
CREATE FUNCTION FN_BRUTTO (NETTO NUMERIC(12,2), SATZ NUMERIC(4,2) = 19)
RETURNS NUMERIC(12,2)
DETERMINISTIC
AS
BEGIN
  RETURN CAST(NETTO * (1 + SATZ / 100) AS NUMERIC(12,2));
END^

/* Package mit Kopf und Rumpf (ab Firebird 3) */
CREATE PACKAGE PKG_SHOP
AS
BEGIN
  FUNCTION KUNDENUMSATZ (P_KUNDE_ID INTEGER) RETURNS NUMERIC(14,2);
  PROCEDURE BESTELLUNG_ANLEGEN (P_KUNDE_ID INTEGER) RETURNS (BESTELLUNG_ID BIGINT);
END^

CREATE PACKAGE BODY PKG_SHOP
AS
BEGIN
  FUNCTION KUNDENUMSATZ (P_KUNDE_ID INTEGER) RETURNS NUMERIC(14,2)
  AS
  BEGIN
    RETURN (SELECT COALESCE(SUM(SUMME_NETTO), 0) FROM BESTELLUNG
             WHERE KUNDE_ID = :P_KUNDE_ID AND STATUS <> 'storniert');
  END

  PROCEDURE BESTELLUNG_ANLEGEN (P_KUNDE_ID INTEGER) RETURNS (BESTELLUNG_ID BIGINT)
  AS
  BEGIN
    INSERT INTO BESTELLUNG (KUNDE_ID, LIEFERADRESSE_ID)
    VALUES (:P_KUNDE_ID,
            (SELECT FIRST 1 ADRESSE_ID FROM ADRESSE
              WHERE KUNDE_ID = :P_KUNDE_ID AND ART = 'L' ORDER BY GUELTIG_AB DESC))
    RETURNING BESTELLUNG_ID INTO :BESTELLUNG_ID;
  END
END^

